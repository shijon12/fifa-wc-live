create extension if not exists pgcrypto;

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(),
  endpoint text not null unique,
  p256dh text not null,
  auth text not null,
  favorite_team_ids text[] not null default '{}',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notification_match_state (
  match_id text primary key,
  home_score integer,
  away_score integer,
  status text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.notification_events (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  match_id text not null,
  team_ids text[] not null,
  title text not null,
  body text not null,
  url text not null,
  created_at timestamptz not null default now()
);

create index if not exists push_subscriptions_favorite_team_ids_idx
  on public.push_subscriptions using gin (favorite_team_ids);

create index if not exists notification_events_created_at_idx
  on public.notification_events (created_at desc);

alter table public.push_subscriptions enable row level security;
alter table public.notification_match_state enable row level security;
alter table public.notification_events enable row level security;

revoke all on public.push_subscriptions from anon, authenticated;
revoke all on public.notification_match_state from anon, authenticated;
revoke all on public.notification_events from anon, authenticated;

grant all on public.push_subscriptions to service_role;
grant all on public.notification_match_state to service_role;
grant all on public.notification_events to service_role;
grant usage, select on sequence public.notification_events_id_seq to service_role;
